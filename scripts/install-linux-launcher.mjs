#!/usr/bin/env node
/**
 * Install (or remove) a Linux launcher for the packaged app.
 *
 * `yarn publish:linux` runs this after packaging, but it is also useful on its
 * own (`yarn launcher:install`) to refresh the menu entry from the artifacts in
 * `release/` without rebuilding.
 *
 * It installs:
 *   ~/.local/share/acdsee-classic/            the packaged payload
 *   ~/.local/bin/acdsee-classic               a tiny launcher shim
 *   ~/.local/share/applications/*.desktop     the application-menu entry
 *   ~/<Desktop>/*.desktop                     a desktop icon
 *   ~/.local/share/icons/hicolor/NxN/apps/    the app icon at all standard sizes
 */
import {
  chmodSync,
  copyFileSync,
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync
} from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const slug = pkg.name; // "acdsee-classic" — matches the Linux binary and WM class
const displayName = "ACDSee Classic";
const uninstall = process.argv.includes("--uninstall");

const home = homedir();
const dataHome = process.env.XDG_DATA_HOME || join(home, ".local", "share");

const appDir = join(dataHome, slug);
const binDir = join(home, ".local", "bin");
const shimPath = join(binDir, slug);
const iconRoot = join(dataHome, "icons", "hicolor");
const iconSizes = [16, 24, 32, 48, 64, 128, 256, 512, 1024];
const iconPath = (size) => join(iconRoot, `${size}x${size}`, "apps", `${slug}.png`);
const appsDir = join(dataHome, "applications");
const menuEntry = join(appsDir, `${slug}.desktop`);

/** Run a helper command, returning stdout on success and null on any failure. */
function run(command, args) {
  try {
    const result = spawnSync(command, args, { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] });
    return result.status === 0 ? result.stdout : null;
  } catch {
    return null;
  }
}

/** XDG desktop directory, falling back to ~/Desktop when xdg-user-dir is absent. */
function desktopDir() {
  const value = run("xdg-user-dir", ["DESKTOP"])?.trim();
  return value && value !== home ? value : join(home, "Desktop");
}

/** Prefer the newest AppImage; fall back to electron-builder's unpacked tree. */
function findPayload() {
  const releaseDir = join(root, "release");
  if (!existsSync(releaseDir)) return null;

  const appImages = readdirSync(releaseDir)
    .filter((name) => name.toLowerCase().endsWith(".appimage"))
    .map((name) => join(releaseDir, name))
    .sort((a, b) => statSync(b).mtimeMs - statSync(a).mtimeMs);
  if (appImages.length > 0) return { kind: "appimage", path: appImages[0] };

  const unpackedDir = join(releaseDir, "linux-unpacked");
  const binary = join(unpackedDir, slug);
  if (existsSync(binary)) return { kind: "unpacked", dir: unpackedDir, binary };

  return null;
}

/** Quote a path for a POSIX shell. */
function shellQuote(path) {
  return `'${path.replace(/'/g, "'\\''")}'`;
}

/** Quote a value for the Desktop Entry Exec key. */
function desktopExecQuote(path) {
  return `"${path.replace(/(["\\`$])/g, "\\$1")}"`;
}

function refreshCaches() {
  run("update-desktop-database", [appsDir]);
  run("gtk-update-icon-cache", ["-f", "-t", join(dataHome, "icons", "hicolor")]);
}

function uninstallLauncher() {
  for (const path of [menuEntry, join(desktopDir(), `${slug}.desktop`)]) {
    rmSync(path, { force: true });
  }
  for (const size of iconSizes) {
    rmSync(iconPath(size), { force: true });
  }
  rmSync(shimPath, { force: true });
  rmSync(appDir, { recursive: true, force: true });
  refreshCaches();
  console.log(`Removed the ${displayName} launcher.`);
}

function installLauncher() {
  const payload = findPayload();
  if (!payload) {
    console.error(
      `No Linux package found in ${join(root, "release")}.\n` +
        "Run `yarn dist:linux` (or `yarn publish:linux`) first."
    );
    process.exit(1);
  }

  // Replace the payload so launcher and package always match.
  rmSync(appDir, { recursive: true, force: true });
  mkdirSync(appDir, { recursive: true });

  let executable;
  if (payload.kind === "appimage") {
    executable = join(appDir, `${slug}.AppImage`);
    copyFileSync(payload.path, executable);
  } else {
    const target = join(appDir, "app");
    cpSync(payload.dir, target, { recursive: true });
    executable = join(target, slug);
  }
  chmodSync(executable, 0o755);

  // Stable shim: the .desktop entry and PATH both point here.
  mkdirSync(binDir, { recursive: true });
  writeFileSync(
    shimPath,
    `#!/bin/sh\n# Generated by \`yarn publish:linux\` — safe to delete.\nexec ${shellQuote(executable)} "$@"\n`,
    "utf8"
  );
  chmodSync(shimPath, 0o755);

  // App icon at every hicolor size (the .desktop file refers to it by name).
  for (const size of iconSizes) {
    const dir = join(iconRoot, `${size}x${size}`, "apps");
    const source = join(root, "resources", "icons", `${size}x${size}.png`);
    mkdirSync(dir, { recursive: true });
    copyFileSync(existsSync(source) ? source : join(root, "resources", "icon.png"), iconPath(size));
  }

  const desktopEntry = [
    "[Desktop Entry]",
    "Type=Application",
    "Version=1.0",
    `Name=${displayName}`,
    "GenericName=Image Browser",
    "Comment=Classic ACDSee 3.x image browser for your photo folders",
    `Exec=${desktopExecQuote(shimPath)}`,
    `TryExec=${shimPath}`,
    `Icon=${slug}`,
    "Terminal=false",
    "Categories=Graphics;Viewer;",
    "Keywords=image;photo;viewer;browser;acdsee;",
    `StartupWMClass=${slug}`,
    "MimeType=image/jpeg;image/png;image/gif;image/bmp;image/tiff;image/webp;",
    ""
  ].join("\n");

  mkdirSync(appsDir, { recursive: true });
  writeFileSync(menuEntry, desktopEntry, "utf8");

  const desktopCopy = join(desktopDir(), `${slug}.desktop`);
  mkdirSync(desktopDir(), { recursive: true });
  writeFileSync(desktopCopy, desktopEntry, "utf8");
  chmodSync(menuEntry, 0o755);
  chmodSync(desktopCopy, 0o755);
  // XFCE/GNOME only run desktop launchers they consider trusted.
  run("gio", ["set", desktopCopy, "metadata::trusted", "true"]);

  refreshCaches();

  console.log(`Installed ${displayName} ${pkg.version}`);
  console.log(`  Payload:      ${executable}`);
  console.log(`  Command:      ${shimPath}`);
  console.log(`  Menu entry:   ${menuEntry}`);
  console.log(`  Desktop icon: ${desktopCopy}`);
  console.log("Launch it from your application menu or double-click the desktop icon.");
}

if (uninstall) uninstallLauncher();
else installLauncher();
